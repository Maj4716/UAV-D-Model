"""Engine-equivalence check: does the current working tree reproduce the teacher?

The formal dataset was generated by engine build sha256:b041499a...; the proxy
runs on the current shared working tree (different source-tree hash because
unrelated modules were edited).  Re-running the full DamageEngine on a sample of
train cases and comparing the physics outputs with the archived teacher rows
tests whether every module the proxy shares with the teacher (fragment source,
geometry, penetration kernel, damage accumulation) is still bit-equivalent.

Usage: python check_teacher_equivalence.py [N_PER_PROFILE]   (default 4)
Writes results/teacher_equivalence_check.json.  Train/validation rows only.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from common import DATASET, PHYSICS, ROOT, STUDY, TARGET  # noqa: E402

sys.path.insert(0, str(ROOT))
from damage_engine.engine import ENGINE_CODE_HASH, DamageEngine  # noqa: E402
from damage_engine.registry import PhysicsRegistry  # noqa: E402
from tools.evaluate_proxy_teacher_distribution import load_development_evidence  # noqa: E402

OUT = STUDY / "results" / "teacher_equivalence_check.json"


def physics_view(result: dict) -> dict:
    view = {}
    for component_id, record in result["components"].items():
        fm = record["fragment_metrics"]
        view[component_id] = {
            "hit": fm["hit_indicator"]["mean"],
            "hits": fm["hits"]["mean"],
            "deposited": fm["deposited_energy_j"]["mean"],
            "states": {
                state: record["damage_states"]["fragment"][state]["mean"]
                for state in record["damage_states"]["fragment"]
            },
        }
    view["summary_component_hits"] = result["summary"]["total_component_hits"]["mean"]
    view["summary_armor_hits"] = result["summary"]["total_armor_hits"]["mean"]
    view["affected_fraction"] = result["penetration_domain_coverage"]["affected_replicate_fraction"]
    return view


def main(argv: list[str]) -> int:
    per_profile = int(argv[0]) if argv else 4
    evidence, audit = load_development_evidence(DATASET)
    assert audit["test_result_json_lines_decoded"] == 0
    engine = DamageEngine(
        json.loads(TARGET.read_text(encoding="utf-8-sig")),
        PhysicsRegistry.from_file(PHYSICS),
    )
    chosen, seen = [], {}
    for item in evidence:
        if item.split != "train":
            continue
        profile = item.case["munition"]["profile_id"]
        if seen.get(profile, 0) < per_profile:
            seen[profile] = seen.get(profile, 0) + 1
            chosen.append(item)
    rows = []
    for item in chosen:
        fresh = engine.run(json.loads(json.dumps(item.case))).to_dict()
        old, new = physics_view(item.result), physics_view(fresh)
        rows.append(
            {
                "case_id": item.case["case_id"],
                "profile": item.case["munition"]["profile_id"],
                "identical": old == new,
            }
        )
        print(rows[-1], flush=True)
    report = {
        "teacher_engine_code_hash": audit["source_engine"]["code_hash"],
        "current_engine_code_hash": ENGINE_CODE_HASH,
        "cases_checked": len(rows),
        "all_identical": all(row["identical"] for row in rows),
        "compared_fields": "per component fragment hit_indicator/hits/deposited_energy means and fragment damage-state means; summary hit counts; affected replicate fraction",
        "rows": rows,
    }
    OUT.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps({k: v for k, v in report.items() if k != "rows"}, indent=2))
    return 0 if report["all_identical"] else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
